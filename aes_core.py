# Bang hang so vong Round Constants (Rcon)
RCON = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36
]


def gmul(a: int, b: int) -> int:
    """Nhan hai phan tu tren truong Galois GF(2^8) modulo m(x) = x^8 + x^4 + x^3 + x + 1 (0x11B)"""
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi_bit = a & 0x80
        a = (a << 1) & 0xFF
        if hi_bit:
            a ^= 0x1B
        b >>= 1
    return p


class AES128:
    """
    Lop cai dat thuat toan AES-128:
    - Kich thuoc khoi (Block Size): 128 bit (16 bytes)
    - Kich thuoc khoa (Key Size): 128 bit (16 bytes)
    - So vong ma hoa (Rounds): 10
    """
    def __init__(self, key: bytes):
        if len(key) != 16:
            raise ValueError("AES-128 yeu cau khoa dung 16 bytes (128-bit)!")
        self.key = key
        self.round_keys = self._key_expansion(key)

    @staticmethod
    def _bytes_to_matrix(data: bytes) -> list[list[int]]:
        """Chuyen mang 16 bytes thanh ma tran State 4x4 theo thu tu cot (Column-major)"""
        return [[data[r + 4 * c] for c in range(4)] for r in range(4)]

    @staticmethod
    def _matrix_to_bytes(matrix: list[list[int]]) -> bytes:
        """Chuyen ma tran State 4x4 ve mang 16 bytes theo thu tu cot"""
        res = bytearray(16)
        for r in range(4):
            for c in range(4):
                res[r + 4 * c] = matrix[r][c]
        return bytes(res)

    def _key_expansion(self, key: bytes) -> list[list[list[int]]]:
        """
        Mo rong khoa (Key Expansion):
        Tu khoa 16 bytes ban dau tao ra 11 khoa vong (Round Keys),
        moi khoa vong la mot ma tran 4x4.
        """
        words = []
        for i in range(4):
            words.append([key[4 * i], key[4 * i + 1], key[4 * i + 2], key[4 * i + 3]])

        for i in range(4, 44):
            temp = list(words[i - 1])
            if i % 4 == 0:
                # RotWord: dich trai 1 byte
                temp = temp[1:] + temp[:1]
                # SubWord: qua S-Box
                temp = [S_BOX[b] for b in temp]
                # XOR voi Rcon
                temp[0] ^= RCON[i // 4]
            # XOR voi word[i - 4]
            word = [words[i - 4][b] ^ temp[b] for b in range(4)]
            words.append(word)

        # Chuyen 44 words thanh 11 ma tran khoa vong 4x4 (moi round key gom 4 words lam 4 cot)
        round_keys = []
        for r in range(11):
            rk_matrix = [[0] * 4 for _ in range(4)]
            for c in range(4):
                w = words[r * 4 + c]
                for row in range(4):
                    rk_matrix[row][c] = w[row]
            round_keys.append(rk_matrix)
        return round_keys

    @staticmethod
    def _sub_bytes(state: list[list[int]]):
        """Phep bien doi SubBytes: Thay the tung byte trong State qua S-Box"""
        for r in range(4):
            for c in range(4):
                state[r][c] = S_BOX[state[r][c]]

    @staticmethod
    def _inv_sub_bytes(state: list[list[int]]):
        """Phep bien doi nghich dao InvSubBytes: Qua InvS-Box"""
        for r in range(4):
            for c in range(4):
                state[r][c] = INV_S_BOX[state[r][c]]

    @staticmethod
    def _shift_rows(state: list[list[int]]):
        """Phep bien doi ShiftRows: Dich vong trai hang i boi i vi tri"""
        state[1] = state[1][1:] + state[1][:1]
        state[2] = state[2][2:] + state[2][:2]
        state[3] = state[3][3:] + state[3][:3]

    @staticmethod
    def _inv_shift_rows(state: list[list[int]]):
        """Phep bien doi nghich dao InvShiftRows: Dich vong phai hang i boi i vi tri"""
        state[1] = state[1][-1:] + state[1][:-1]
        state[2] = state[2][-2:] + state[2][:-2]
        state[3] = state[3][-3:] + state[3][:-3]

    @staticmethod
    def _mix_columns(state: list[list[int]]):
        """
        Phep bien doi MixColumns: Nhan ma tran State voi da thuc co dinh tren GF(2^8):
        [2 3 1 1]
        [1 2 3 1]
        [1 1 2 3]
        [3 1 1 2]
        """
        for c in range(4):
            s0, s1, s2, s3 = state[0][c], state[1][c], state[2][c], state[3][c]
            state[0][c] = gmul(2, s0) ^ gmul(3, s1) ^ s2 ^ s3
            state[1][c] = s0 ^ gmul(2, s1) ^ gmul(3, s2) ^ s3
            state[2][c] = s0 ^ s1 ^ gmul(2, s2) ^ gmul(3, s3)
            state[3][c] = gmul(3, s0) ^ s1 ^ s2 ^ gmul(2, s3)

    @staticmethod
    def _inv_mix_columns(state: list[list[int]]):
        """
        Phep bien doi nghich dao InvMixColumns: Nhan ma tran State tren GF(2^8):
        [0e 0b 0d 09]
        [09 0e 0b 0d]
        [0d 09 0e 0b]
        [0b 0d 09 0e]
        """
        for c in range(4):
            s0, s1, s2, s3 = state[0][c], state[1][c], state[2][c], state[3][c]
            state[0][c] = gmul(0x0e, s0) ^ gmul(0x0b, s1) ^ gmul(0x0d, s2) ^ gmul(0x09, s3)
            state[1][c] = gmul(0x09, s0) ^ gmul(0x0e, s1) ^ gmul(0x0b, s2) ^ gmul(0x0d, s3)
            state[2][c] = gmul(0x0d, s0) ^ gmul(0x09, s1) ^ gmul(0x0e, s2) ^ gmul(0x0b, s3)
            state[3][c] = gmul(0x0b, s0) ^ gmul(0x0d, s1) ^ gmul(0x09, s2) ^ gmul(0x0e, s3)

    @staticmethod
    def _add_round_key(state: list[list[int]], round_key: list[list[int]]):
        """Phep bien doi AddRoundKey: XOR State voi RoundKey"""
        for r in range(4):
            for c in range(4):
                state[r][c] ^= round_key[r][c]

    def encrypt_block(self, plaintext_block: bytes) -> bytes:
        """Ma hoa 1 khoi don 16 bytes bang AES-128"""
        if len(plaintext_block) != 16:
            raise ValueError("Kich thuoc khoi phai dung 16 bytes!")

        state = self._bytes_to_matrix(plaintext_block)

        # Vong khoi dau (Round 0)
        self._add_round_key(state, self.round_keys[0])

        # Vong 1 -> 9
        for r in range(1, 10):
            self._sub_bytes(state)
            self._shift_rows(state)
            self._mix_columns(state)
            self._add_round_key(state, self.round_keys[r])

        # Vong cuoi (Round 10 - khong co MixColumns)
        self._sub_bytes(state)
        self._shift_rows(state)
        self._add_round_key(state, self.round_keys[10])

        return self._matrix_to_bytes(state)

    def decrypt_block(self, ciphertext_block: bytes) -> bytes:
        """Giai ma 1 khoi don 16 bytes bang AES-128"""
        if len(ciphertext_block) != 16:
            raise ValueError("Kich thuoc khoi phai dung 16 bytes!")

        state = self._bytes_to_matrix(ciphertext_block)

        # Vong khoi dau giai ma (Round 10)
        self._add_round_key(state, self.round_keys[10])

        # Vong 9 ve 1
        for r in range(9, 0, -1):
            self._inv_shift_rows(state)
            self._inv_sub_bytes(state)
            self._add_round_key(state, self.round_keys[r])
            self._inv_mix_columns(state)

        # Vong cuoi (Round 0 - khong co InvMixColumns)
        self._inv_shift_rows(state)
        self._inv_sub_bytes(state)
        self._add_round_key(state, self.round_keys[0])

        return self._matrix_to_bytes(state)
